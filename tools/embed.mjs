// Packs the runtime and source-project templates into builder/js/templates.js so the
// builder works from a plain file:// open, with no server and no fetch().
// Run after changing anything in runtime/ or source-template/:  node tools/embed.mjs
import { readFileSync, readdirSync, statSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const walk = dir => readdirSync(dir).flatMap(n => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));
const read = (base) => Object.fromEntries(walk(base).sort().map(f => [relative(base, f).split('\\').join('/'), readFileSync(f, 'utf8')]));

// Icons (Lucide, ISC licence) and the colour chart (Tailwind CSS palette, MIT licence).
const FORM_ICONS = ['clipboard-list', 'clipboard-check', 'house', 'users', 'user', 'baby', 'stethoscope', 'syringe', 'pill', 'hospital', 'heart-pulse', 'thermometer', 'test-tube', 'droplets', 'bug', 'bed-double', 'sprout', 'wheat', 'tractor', 'milk', 'egg', 'fish', 'trees', 'school', 'book-open', 'graduation-cap', 'map-pin', 'map', 'camera', 'package', 'truck', 'wallet', 'shopping-cart', 'scale', 'ruler', 'calendar', 'file-text', 'notebook-pen', 'phone', 'building', 'shield-check', 'recycle', 'zap', 'cloud-rain', 'hand-heart', 'star', 'triangle-alert', 'message-square-text'];
const UI_ICONS = ['plus', 'upload', 'download', 'folder-open', 'save', 'copy', 'check', 'x', 'triangle-alert', 'info', 'arrow-left', 'arrow-right', 'arrow-up', 'arrow-down', 'trash-2', 'file-plus', 'layout-grid', 'list', 'palette', 'image', 'smartphone', 'chevron-right', 'external-link', 'eye', 'sun', 'moon', 'file-up', 'refresh-cw', 'layers', 'file-json', 'circle-check', 'circle-x', 'circle-alert', 'pencil-line', 'message-square-text', 'clipboard-paste', 'pipette', 'swatch-book', 'file-text', 'type', 'align-left', 'hash', 'percent', 'circle-dot', 'list-checks', 'gauge', 'calendar-clock', 'calendar-range', 'timer', 'mail', 'pen-line', 'mic', 'video', 'scan-line', 'paperclip', 'git-branch', 'chevron-down', 'chevron-up', 'play', 'list-plus', 'languages', 'settings-2', 'shapes', 'circle-help', 'clock', 'code'];
const iconDir = join(root, 'node_modules/lucide-static/icons');
const inner = n => {
  const s = readFileSync(join(iconDir, n + '.svg'), 'utf8');
  return s.slice(s.indexOf('>', s.indexOf('<svg')) + 1, s.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').trim();
};
const formIcons = Object.fromEntries(FORM_ICONS.map(n => [n, inner(n)]));
const allIcons = Object.fromEntries([...new Set([...FORM_ICONS, ...UI_ICONS])].map(n => [n, inner(n)]));
const iconJs = (name, obj) => `/* Generated by tools/embed.mjs. Icons: Lucide (https://lucide.dev), ISC licence. */
(function (root) {
  var I = ${JSON.stringify(obj)};
  if (typeof module === 'object' && module.exports) module.exports = I;
  else root.${name} = I;
})(typeof self !== 'undefined' ? self : this);
`;
writeFileSync(join(root, 'runtime/simple/icons.js'), iconJs('ODE_ICONS', formIcons));
if (existsSync(join(root, 'runtime/react'))) writeFileSync(join(root, 'runtime/react/icons.js'), iconJs('ODE_ICONS', formIcons));
writeFileSync(join(root, 'builder/js/icons.js'), iconJs('ODE_ICONS', allIcons) + `(function (root) { root.ODE_FORM_ICONS = ${JSON.stringify(FORM_ICONS)}; })(typeof self !== 'undefined' ? self : this);\n`);

const tw = (await import('tailwindcss/colors.js')).default;
const HUES = ['slate', 'stone', 'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'];
const SHADES = ['100', '200', '300', '400', '500', '600', '700', '800', '900'];
const chart = HUES.map(h => ({ name: h[0].toUpperCase() + h.slice(1), shades: SHADES.map(s => tw[h][s].toUpperCase()) }));
writeFileSync(join(root, 'builder/js/colors.js'), `/* Generated by tools/embed.mjs. Colour chart: Tailwind CSS palette (MIT licence). */
(function (root) { root.ODE_COLOR_CHART = ${JSON.stringify({ shades: SHADES, hues: chart })}; })(typeof self !== 'undefined' ? self : this);
`);
console.log('icons:', Object.keys(allIcons).length, 'chart hues:', chart.length);

const templates = {};
for (const name of readdirSync(join(root, 'runtime')).sort((a, b) => (a === 'simple' ? -1 : b === 'simple' ? 1 : a.localeCompare(b)))) {
  const source = read(join(root, 'source-template', name));
  source['scripts/builder-core.cjs'] = readFileSync(join(root, 'builder/js/core.js'), 'utf8');
  if (name === 'react') source['public/icons.js'] = readFileSync(join(root, 'runtime/simple/icons.js'), 'utf8');
  templates[name] = { runtime: read(join(root, 'runtime', name)), source };
}
const meta = {
  simple: { title: 'Plain JavaScript', description: 'No build step. Home screen, record lists and record pages in one small script you can edit in any text editor.' },
  react: { title: 'React starter', description: 'The same screens written in React and TypeScript with Vite, for developers who want to grow the app. Ships ready to use.' },
};
for (const k of Object.keys(templates)) templates[k].meta = meta[k] || { title: k, description: '' };

const js = `/* Generated by tools/embed.mjs. Do not edit; edit runtime/ and source-template/ instead. */
(function (root) {
  var T = ${JSON.stringify(templates, null, 0)};
  if (typeof module === 'object' && module.exports) module.exports = T;
  else root.ODE_TEMPLATES = T;
})(typeof self !== 'undefined' ? self : this);
`;
writeFileSync(join(root, 'builder/js/templates.js'), js);
console.log('templates:', Object.keys(templates).map(k => `${k} (${Object.keys(templates[k].runtime).length} runtime, ${Object.keys(templates[k].source).length} source files)`).join(', '));

// Examples: examples/<id>/project.json + forms/<type>/{schema,ui}.json
const examples = {};
for (const id of readdirSync(join(root, 'examples'))) {
  const dir = join(root, 'examples', id);
  const p = JSON.parse(readFileSync(join(dir, 'project.json'), 'utf8'));
  for (const f of p.forms) {
    f.schemaText = readFileSync(join(dir, 'forms', f.formType, 'schema.json'), 'utf8');
    f.uiText = readFileSync(join(dir, 'forms', f.formType, 'ui.json'), 'utf8');
  }
  examples[id] = p;
}
writeFileSync(join(root, 'builder/js/examples.js'), `/* Generated by tools/embed.mjs from examples/. */
(function (root) {
  var E = ${JSON.stringify(examples)};
  if (typeof module === 'object' && module.exports) module.exports = E;
  else root.ODE_EXAMPLES = E;
})(typeof self !== 'undefined' ? self : this);
`);
console.log('examples:', Object.keys(examples).join(', '));


// Templates gallery: gallery/templates.txt compiled with the question editor's form model.
const { buildGallery } = await import('./gallery.mjs');
const gallery = buildGallery(readFileSync(join(root, 'gallery/templates.txt'), 'utf8'));
for (const [id, p] of Object.entries(gallery)) {
  for (const f of p.forms) { delete f.schemaText; delete f.uiText; } // compiled from the model on load
  for (const icon of [p.gallery.icon, ...p.forms.map(f => f.icon)]) if (!FORM_ICONS.includes(icon)) throw new Error(`gallery ${id}: icon ${icon} is not a form icon`);
}
writeFileSync(join(root, 'builder/js/gallery.js'), `/* Generated by tools/embed.mjs from gallery/templates.txt. */
(function (root) {
  var G = ${JSON.stringify(gallery)};
  if (typeof module === 'object' && module.exports) module.exports = G;
  else root.ODE_GALLERY = G;
})(typeof self !== 'undefined' ? self : this);
`);
console.log('gallery:', Object.keys(gallery).join(', '));
